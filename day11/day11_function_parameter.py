# 下面是函数各种传参。包括位置参数、默认参数（缺省参数）、可变参数、关键字参数、命名关键字参数、不定长传参等。

# 位置参数：调用函数时，根据函数定义的参数位置来传递参数值。这里的参数值必须按照固定位置来传参。

# 关键字参数：调用函数时，使用参数名来指定参数值，可以不按照函数定义的参数位置来传递参数值。
# 关键字传参语法：函数名(参数名=参数值, ...)
# 关键字传参可以与位置参数混合使用，但位置参数必须在关键字参数之前。
# 默认参数：在函数定义时为参数指定默认值，如果调用函数时没有传递该参数的值，则使用默认值。
# 默认参数必须放在位置参数的后面，否则会导致语法错误。

# 示例：
def greet(name, greeting="Hello"):
    print(f"{greeting}, {name}!")   # 输出：Hello, Alice!

greet("Alice")    # 使用默认参数greeting的值
greet("Bob", "Hi")   # 使用传递的参数greeting的值

# 可变参数：在函数定义时使用*args来表示可变位置参数，使用**kwargs来表示可变关键字参数。可变参数允许函数接受任意数量的位置参数或关键字参数。这个也就是不定长参数
# 可变位置参数会被收集到一个元组中，而可变关键字参数会被收集到字典中。
# 示例：
def func(*args, **kwargs):
    print("位置参数：", args)   # 输出：位置参数： (1, 2, 3)
    print("关键字参数：", kwargs)   # 输出：关键字参数： {'a': 4, 'b': 5}
